"""Behavioral gate: no scripted world cognition; real local research is isolated.

The tests intentionally forbid "pond" or "shed" answers generated by the
removed rules. Passing an abstention test is not proof of intelligence.
"""
import io
import json
import tempfile
import unittest
import urllib.error
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

from LLM_Training import read_records, run_session
from sonara_memory import SonaraMemorySystem
from sonara_research import (
    DEFAULT_LOCAL_MODEL, LOCAL_ENDPOINT, ResearchCognition, ResearchModel,
    ollama_local_generate,
)


class LiveBoundaryTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)

    def drive(self, entries, **kwargs):
        with patch("builtins.input", side_effect=entries):
            run_session(self.root, **kwargs)

    def test_observations_persist_but_unlearned_questions_abstain(self):
        # Leave an old obsolete classifier checkpoint: session must ignore it.
        (self.root / "world_model.pt").write_bytes(b"obsolete classifier")
        self.drive([
            "Jake moved the ball into the pond.",
            "Jake moved the ball into the shed.",
            "/ask Where is the ball?",
            "/ask Where was the ball before it was at the shed?",
            "/quit",
        ])
        memories = SonaraMemorySystem(self.root / "sonara_memories")
        self.assertEqual(len(memories.memories), 2)
        self.assertEqual([m.semantic_frame for m in memories.memories.values()], [{}, {}])
        self.assertTrue(all(m.source == "user_observation" for m in memories.memories.values()))
        self.assertTrue(any("pond" in m.content for m in memories.memories.values()))
        self.assertTrue(any("shed" in m.content for m in memories.memories.values()))
        events = read_records(self.root / "events.jsonl")
        answers = [r for r in events if r.get("type") == "abstention"]
        self.assertEqual(len(answers), 2)
        self.assertTrue(all(r["verification"] == "unknown" for r in answers))
        self.assertTrue(all("UNKNOWN: No trained world-question answering" in r["text"]
                            for r in answers))

        self.drive(["/ask Where is the ball?", "/recall ball", "/quit"])
        persisted = SonaraMemorySystem(self.root / "sonara_memories")
        self.assertEqual(len(persisted.memories), 2)
        events = read_records(self.root / "events.jsonl")
        answers = [r for r in events if r.get("type") == "abstention"]
        self.assertEqual(len(answers), 3)
        self.assertTrue(all("UNKNOWN" in r["text"] for r in answers))
        self.assertEqual(len(read_records(self.root / "candidates.jsonl")), 2)
        self.assertFalse((self.root / "learning_events.jsonl").exists())

    def test_no_heuristic_reflection_or_pseudo_world_learning(self):
        self.drive([
            "Jake moved the ball into the pond.",
            "Jake moved the ball into the shed.",
            "/reflect",
            "/train-world",
            "/feedback pond",
            "/quit",
        ])
        memories = SonaraMemorySystem(self.root / "sonara_memories")
        self.assertEqual(len(memories.memories), 2)
        self.assertFalse(any(m.category == "reflection" for m in memories.memories.values()))
        self.assertFalse((self.root / "world_model.pt").exists())
        # Legacy auto-generated statements remain archived but are not searchable as facts.
        memories.remember("Synthetic insight: Jake has a preference for ponds.",
                          category="reflection", source="sonara_reflection")
        self.assertFalse(any(m.source == "sonara_reflection" for m, _ in
                             memories.recall("Synthetic insight Jake preference ponds")))

    def test_local_research_feedback_trains_only_utility_head(self):
        sent = []
        research = ResearchCognition(self.root, transport=lambda q, m: sent.append((q, m)) or "Tentative.")
        result = research.research("Why do some objects float?")
        self.assertEqual(sent, [("Why do some objects float?", DEFAULT_LOCAL_MODEL)])
        self.assertEqual(result["status"], "unverified_local_model_output")
        before = research.expected_utility(result["question"])
        trained = research.feedback(result["question"], 0.9)
        self.assertTrue(trained["trained"])
        self.assertLess(trained["utility_error_after"], trained["utility_error_before"])
        reloaded = ResearchCognition(self.root, transport=lambda *_: "Not a fact")
        self.assertIsInstance(reloaded.model, ResearchModel)
        self.assertAlmostEqual(reloaded.expected_utility(result["question"]),
                               research.expected_utility(result["question"]), places=6)
        self.assertNotEqual(before, research.expected_utility(result["question"]))
        self.assertEqual(len(SonaraMemorySystem(self.root / "sonara_memories").memories), 0)
        self.assertFalse((self.root / "world_model.pt").exists())

    def test_research_on_live_session_never_promotes_answer(self):
        with patch("sonara_research.ollama_local_generate", return_value="Hypothesis only.") as ollama:
            self.drive(["/research Why do some objects float?", "/rate-research 0.8", "/quit"],
                       enable_research=True)
        ollama.assert_called_once_with("Why do some objects float?", DEFAULT_LOCAL_MODEL)
        records = read_records(self.root / "research_events.jsonl")
        feedback = read_records(self.root / "research_feedback.jsonl")
        self.assertEqual(len(records), 1)
        self.assertEqual(records[0]["source"], "local_model")
        self.assertEqual(records[0]["status"], "unverified_local_model_output")
        self.assertEqual(len(feedback), 1)
        self.assertEqual(len(SonaraMemorySystem(self.root / "sonara_memories").memories), 0)

    def test_disabled_research_never_contacts_ollama(self):
        with patch("sonara_research.ollama_local_generate") as remote:
            self.drive(["/research Why?", "/quit"], enable_research=False)
            remote.assert_not_called()

    def test_ollama_requests_are_loopback_only(self):
        with patch("sonara_research.urllib.request.build_opener") as opener:
            opener.return_value.open.return_value = io.BytesIO(b'{"response":"Local hypothesis"}')
            self.assertEqual(ollama_local_generate("Why?", DEFAULT_LOCAL_MODEL),
                             "Local hypothesis")
            request = opener.return_value.open.call_args.args[0]
            self.assertEqual(request.full_url, LOCAL_ENDPOINT)
            self.assertEqual(json.loads(request.data)["prompt"], "Why?")
        with patch("sonara_research.urllib.request.build_opener") as opener:
            opener.return_value.open.side_effect = urllib.error.URLError("no server")
            with self.assertRaisesRegex(ValueError, "ollama serve"):
                ollama_local_generate("Why?", DEFAULT_LOCAL_MODEL)
        with self.assertRaises(ValueError):
            ollama_local_generate("Why?", "https://another-server")


    def test_adaptive_recall_uses_existing_user_memory_not_generated_facts(self):
        self.drive(["Jake moved the ball into the shed.",
                    "/ask Where is the ball?", "/quit"], enable_adaptive_loop=True)
        events = read_records(self.root / "events.jsonl")
        retrieved = [event for event in events if event.get("type") == "evidence_retrieval"]
        self.assertEqual(len(retrieved), 1)
        self.assertEqual(retrieved[0]["verification"], "user_evidence_only")
        self.assertIn("Jake moved the ball into the shed.", retrieved[0]["text"])
        self.assertEqual(len(SonaraMemorySystem(self.root / "sonara_memories").memories), 1)
        self.assertFalse((self.root / "learning_events.jsonl").exists())

    def test_adaptive_feedback_changes_live_action_and_survives_restart(self):
        example = SimpleNamespace(answer="shed", confidence=0.40, uncertainty=1.0)
        with patch("sonara_world_model.SonaraWorldModel") as model_type:
            model_type.return_value.predict.return_value = example
            self.drive(["/ask Where is the ball?", "/rate-answer 0",
                        "/ask Where is the ball?", "/quit"],
                       enable_world_model=True, enable_adaptive_loop=True)
            self.drive(["/ask Where is the ball?", "/quit"],
                       enable_world_model=True, enable_adaptive_loop=True)
        events = read_records(self.root / "events.jsonl")
        answers = [e for e in events if e.get("type") in ("neural_prediction", "abstention")]
        feedback = [e for e in events if e.get("type") == "adaptive_feedback"]
        self.assertEqual([e["type"] for e in answers],
                         ["neural_prediction", "abstention", "abstention"])
        self.assertEqual(len(feedback), 1)
        self.assertEqual(feedback[0]["source"], "user")
        self.assertEqual(answers[-1]["adaptive_gate"]["matching_ratings"], 1)
        self.assertFalse((self.root / "world_model.pt").exists())
        self.assertEqual(len(SonaraMemorySystem(self.root / "sonara_memories").memories), 0)


if __name__ == "__main__":
    unittest.main()
